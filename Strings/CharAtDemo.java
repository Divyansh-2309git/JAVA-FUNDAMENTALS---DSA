/**
 * Program Name : CharAtDemo
 * Topic        : Strings
 * Difficulty   : Beginner
 * Concepts     : String Indexing, charAt() Method
 * -------------------------------------------------------------
 * Description  :
 * Demonstrates how to access individual characters in a String using 0-based indexing.
 */
public class CharAtDemo {
    public static void main(String[] args) {
        String name = "Divyansh";
        
        // Access character at index 1 ('i')
        System.out.println("Character at index 1 of \"" + name + "\": " + name.charAt(1));
    }
}
