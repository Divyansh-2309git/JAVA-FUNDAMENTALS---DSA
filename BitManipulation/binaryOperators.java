public class binaryOperators {
    public static void main(String[] args) {
        System.out.println(5 & 6 );//! AND operator 
        System.out.println(5 | 6 );//! OR operator 
        System.out.println(5 ^ 6 ); //! XOR operator 
        System.out.println(~5); //! NOt operator 
        System.out.println(~(~5));
        System.out.println(6<<1);//! Left shift operator 
        System.out.println(6>> 2 ) ; //! Right shift operator 

    }
}
